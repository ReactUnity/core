namespace ReactUnity.Types
{
    /// <summary>
    /// The <c>scroll-behavior</c> property: whether a scroll the element is *asked* to make animates
    /// instead of jumping. A wheel or a drag keeps its own smoothing either way, as on the web.
    /// </summary>
    public enum ScrollBehavior
    {
        Auto = 0,
        Smooth = 1,
    }
}
